import React, { useState } from 'react';
import {
  Calendar,
  CheckCircle2,
  Clock,
  Plus,
  Trash2,
  Filter,
  CheckSquare,
  Sparkles,
  ChevronDown,
  Tag,
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { EventData, TimelineMilestone } from '../types/event';
import { formatDate } from '../utils/formatters';
import { aiGenerateTimeline } from '../services/api';
import { generateDefaultTimeline } from '../data/eventDefaults';

interface TimelineViewProps {
  event: EventData;
  onUpdateTimeline: (timeline: TimelineMilestone[]) => void;
}

export const TimelineView: React.FC<TimelineViewProps> = ({
  event,
  onUpdateTimeline,
}) => {
  const [filterPhase, setFilterPhase] = useState<string>('all');
  const [showAddModal, setShowAddModal] = useState(false);
  const [isGeneratingAI, setIsGeneratingAI] = useState(false);
  const [aiMessage, setAiMessage] = useState<string | null>(null);

  // New milestone form state
  const [newTitle, setNewTitle] = useState('');
  const [newDescription, setNewDescription] = useState('');
  const [newDaysBefore, setNewDaysBefore] = useState('30');
  const [newCategory, setNewCategory] = useState('General');
  const [newPhase, setNewPhase] = useState<TimelineMilestone['phase']>('1_to_2_months');
  const [formError, setFormError] = useState('');

  const milestones = event.timeline;
  const completedCount = milestones.filter((m) => m.isCompleted).length;
  const progressPercent = milestones.length > 0 ? Math.round((completedCount / milestones.length) * 100) : 0;

  // AI Generate Timeline
  const handleAIGenerateTimeline = async () => {
    setIsGeneratingAI(true);
    setAiMessage(null);
    try {
      const res = await aiGenerateTimeline({
        eventType: event.eventType,
        eventDate: event.date,
        name: event.name,
        guestCount: event.guestCount,
      });

      if (res.milestones && res.milestones.length > 0) {
        const eDate = event.date ? new Date(event.date) : null;
        const mapped: TimelineMilestone[] = res.milestones.map((m: any, idx: number) => {
          let calcDate = undefined;
          const days = Number(m.targetDaysBefore) || 0;
          if (eDate && !isNaN(eDate.getTime())) {
            const target = new Date(eDate.getTime() - days * 24 * 60 * 60 * 1000);
            calcDate = target.toISOString().split('T')[0];
          }

          return {
            id: `ai-milestone-${idx + 1}-${Date.now()}`,
            phase: m.phase || '1_to_2_months',
            phaseLabel: m.phaseLabel || 'Upcoming',
            title: m.title,
            description: m.description || '',
            targetDaysBefore: days,
            calculatedDate: calcDate,
            isCompleted: false,
            category: m.category || 'General',
          };
        });

        onUpdateTimeline(mapped);
        confetti({
          particleCount: 50,
          spread: 60,
          origin: { y: 0.7 },
        });
        setAiMessage(res.message || 'Custom timeline generated by Gemini AI!');
      } else {
        const fallback = generateDefaultTimeline(event.date, event.eventType);
        onUpdateTimeline(fallback);
        setAiMessage('Timeline recalculated for your event date.');
      }
    } catch (err) {
      const fallback = generateDefaultTimeline(event.date, event.eventType);
      onUpdateTimeline(fallback);
      setAiMessage('Timeline generated based on standard milestones.');
    } finally {
      setIsGeneratingAI(false);
      setTimeout(() => setAiMessage(null), 5000);
    }
  };

  // Toggle milestone completion
  const handleToggle = (id: string) => {
    const updated = milestones.map((m) => {
      if (m.id === id) {
        const nextState = !m.isCompleted;
        if (nextState) {
          // Trigger light celebratory confetti
          confetti({
            particleCount: 40,
            spread: 50,
            origin: { y: 0.8 },
            colors: ['#a855f7', '#8b5cf6', '#c084fc', '#e9d5ff'],
          });
        }
        return { ...m, isCompleted: nextState };
      }
      return m;
    });

    onUpdateTimeline(updated);

    // If all completed, big celebration
    const allDone = updated.every((m) => m.isCompleted);
    if (allDone && updated.length > 0) {
      confetti({
        particleCount: 120,
        spread: 80,
        origin: { y: 0.6 },
      });
    }
  };

  // Add custom milestone
  const handleAddMilestone = () => {
    if (!newTitle.trim()) {
      setFormError('Title is required');
      return;
    }

    const days = parseInt(newDaysBefore, 10) || 0;
    let targetDateStr: string | undefined = undefined;

    if (event.date) {
      const eDate = new Date(event.date);
      if (!isNaN(eDate.getTime())) {
        const target = new Date(eDate.getTime() - days * 24 * 60 * 60 * 1000);
        targetDateStr = target.toISOString().split('T')[0];
      }
    }

    const newMilestone: TimelineMilestone = {
      id: `custom-milestone-${Date.now()}`,
      phase: newPhase,
      phaseLabel: getPhaseLabel(newPhase),
      title: newTitle.trim(),
      description: newDescription.trim() || 'Custom milestone task',
      targetDaysBefore: days,
      calculatedDate: targetDateStr,
      isCompleted: false,
      category: newCategory.trim() || 'General',
      isCustom: true,
    };

    onUpdateTimeline([...milestones, newMilestone]);

    // Reset form
    setNewTitle('');
    setNewDescription('');
    setNewDaysBefore('30');
    setNewCategory('General');
    setFormError('');
    setShowAddModal(false);
  };

  // Delete custom milestone
  const handleDelete = (id: string) => {
    const updated = milestones.filter((m) => m.id !== id);
    onUpdateTimeline(updated);
  };

  const getPhaseLabel = (phase: TimelineMilestone['phase']) => {
    switch (phase) {
      case '6_plus_months':
        return '6+ Months Before';
      case '3_to_6_months':
        return '3 to 6 Months Before';
      case '1_to_2_months':
        return '1 to 2 Months Before';
      case '2_to_4_weeks':
        return '2 to 4 Weeks Before';
      case 'week_of':
        return 'Week of Event';
      case 'event_day':
        return 'Event Day';
      case 'post_event':
        return 'Post-Event Wrapup';
    }
  };

  // Filtered milestones
  const filteredMilestones = milestones.filter((m) => {
    if (filterPhase === 'all') return true;
    if (filterPhase === 'pending') return !m.isCompleted;
    if (filterPhase === 'completed') return m.isCompleted;
    return m.phase === filterPhase;
  });

  return (
    <div className="space-y-8">
      {/* Header & Timeline Progress */}
      <div className="p-6 rounded-3xl bg-white border border-purple-100 shadow-sm">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-6 pb-6 border-b border-purple-50">
          <div>
            <div className="flex items-center gap-2">
              <span className="p-2 rounded-xl bg-purple-100 text-purple-700">
                <Clock className="w-5 h-5" />
              </span>
              <h2 className="text-xl sm:text-2xl font-bold text-slate-900">
                Preparation Timeline
              </h2>
            </div>
            <p className="text-xs text-slate-500 mt-1">
              Date-based countdown milestones generated for your {event.eventType} on {formatDate(event.date)}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleAIGenerateTimeline}
              disabled={isGeneratingAI}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-gradient-to-r from-purple-600 to-indigo-600 hover:from-purple-700 hover:to-indigo-700 text-white text-xs sm:text-sm font-semibold shadow-xs transition cursor-pointer disabled:opacity-50"
              title="Generate a custom date-based timeline using Gemini AI"
            >
              <Sparkles className={`w-4 h-4 ${isGeneratingAI ? 'animate-spin' : ''}`} />
              <span>{isGeneratingAI ? 'Generating...' : 'AI Generate Timeline'}</span>
            </button>

            <button
              onClick={() => setShowAddModal(true)}
              className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl border border-slate-200 hover:bg-purple-50 text-slate-700 text-xs sm:text-sm font-semibold transition cursor-pointer"
            >
              <Plus className="w-4 h-4" />
              <span>Add Custom</span>
            </button>
          </div>
        </div>

        {aiMessage && (
          <div className="mb-4 p-3 rounded-xl bg-purple-50 border border-purple-200 text-xs font-semibold text-purple-900 flex items-center gap-2 animate-in fade-in">
            <Sparkles className="w-4 h-4 text-purple-600 shrink-0" />
            <span>{aiMessage}</span>
          </div>
        )}

        {/* Progress Bar & Counter */}
        <div className="space-y-2">
          <div className="flex items-center justify-between text-xs font-semibold">
            <span className="text-slate-600">
              Completed Tasks: {completedCount} of {milestones.length}
            </span>
            <span className="text-purple-700 font-bold">{progressPercent}% Completed</span>
          </div>
          <div className="w-full bg-slate-100 rounded-full h-2.5 overflow-hidden">
            <div
              className="h-full bg-gradient-to-r from-purple-600 to-indigo-600 rounded-full transition-all duration-500"
              style={{ width: `${progressPercent}%` }}
            />
          </div>
        </div>

        {/* Phase Filter Tabs */}
        <div className="flex items-center gap-1.5 overflow-x-auto pt-5 text-xs">
          {[
            { id: 'all', label: `All (${milestones.length})` },
            { id: 'pending', label: `Pending (${milestones.filter((m) => !m.isCompleted).length})` },
            { id: 'completed', label: `Completed (${completedCount})` },
            { id: '6_plus_months', label: '6+ Mo' },
            { id: '3_to_6_months', label: '3-6 Mo' },
            { id: '1_to_2_months', label: '1-2 Mo' },
            { id: '2_to_4_weeks', label: '2-4 Wk' },
            { id: 'week_of', label: 'Week of' },
            { id: 'event_day', label: 'Event Day' },
          ].map((tab) => (
            <button
              key={tab.id}
              onClick={() => setFilterPhase(tab.id)}
              className={`px-3 py-1.5 rounded-xl font-medium whitespace-nowrap transition cursor-pointer ${
                filterPhase === tab.id
                  ? 'bg-purple-600 text-white font-semibold shadow-xs'
                  : 'bg-purple-50/50 text-slate-600 hover:bg-purple-100/70'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>
      </div>

      {/* Add Milestone Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 bg-black/40 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-3xl max-w-lg w-full p-6 shadow-2xl border border-purple-100 animate-in fade-in zoom-in-95">
            <div className="flex items-center justify-between pb-4 border-b border-purple-50">
              <h3 className="text-lg font-bold text-slate-900">Add Custom Milestone</h3>
              <button
                onClick={() => setShowAddModal(false)}
                className="text-slate-400 hover:text-slate-600 text-sm font-bold"
              >
                ✕
              </button>
            </div>

            {formError && (
              <p className="text-xs text-rose-600 font-semibold mt-3">{formError}</p>
            )}

            <div className="space-y-4 mt-4">
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  Milestone Task Title *
                </label>
                <input
                  type="text"
                  placeholder="e.g. Schedule hair & makeup trial run"
                  value={newTitle}
                  onChange={(e) => setNewTitle(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-xl border border-purple-200 focus:outline-none focus:ring-2 focus:ring-purple-400"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  Description / Action Items
                </label>
                <textarea
                  rows={2}
                  placeholder="Details, contacts, or checklist points"
                  value={newDescription}
                  onChange={(e) => setNewDescription(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-xl border border-purple-200 focus:outline-none focus:ring-2 focus:ring-purple-400"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    Days Before Event
                  </label>
                  <input
                    type="number"
                    value={newDaysBefore}
                    onChange={(e) => setNewDaysBefore(e.target.value)}
                    className="w-full px-3 py-2 text-xs rounded-xl border border-purple-200"
                    min="0"
                  />
                </div>

                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    Timeline Phase
                  </label>
                  <select
                    value={newPhase}
                    onChange={(e) => setNewPhase(e.target.value as any)}
                    className="w-full px-3 py-2 text-xs rounded-xl border border-purple-200"
                  >
                    <option value="6_plus_months">6+ Months Before</option>
                    <option value="3_to_6_months">3 to 6 Months Before</option>
                    <option value="1_to_2_months">1 to 2 Months Before</option>
                    <option value="2_to_4_weeks">2 to 4 Weeks Before</option>
                    <option value="week_of">Week of Event</option>
                    <option value="event_day">Event Day</option>
                    <option value="post_event">Post-Event Wrapup</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  Category Tag
                </label>
                <input
                  type="text"
                  placeholder="e.g. Attire, Guests, Decor, Catering"
                  value={newCategory}
                  onChange={(e) => setNewCategory(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-xl border border-purple-200"
                />
              </div>

              <div className="flex items-center justify-end gap-2 pt-3 border-t border-purple-50">
                <button
                  onClick={() => setShowAddModal(false)}
                  className="px-4 py-2 rounded-xl text-xs font-semibold text-slate-600 hover:bg-slate-100 transition cursor-pointer"
                >
                  Cancel
                </button>
                <button
                  onClick={handleAddMilestone}
                  className="px-5 py-2 rounded-xl bg-purple-600 hover:bg-purple-700 text-white text-xs font-semibold transition cursor-pointer"
                >
                  Save Milestone
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Milestones Timeline Flow */}
      <div className="space-y-4">
        {filteredMilestones.length === 0 ? (
          <div className="text-center py-12 bg-white rounded-3xl border border-purple-100 text-slate-400 text-xs">
            No milestones match this filter.
          </div>
        ) : (
          filteredMilestones.map((m) => (
            <div
              key={m.id}
              className={`p-5 rounded-2xl bg-white border transition flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 ${
                m.isCompleted
                  ? 'border-slate-100 bg-slate-50/50 opacity-70'
                  : 'border-purple-100/90 hover:border-purple-300 shadow-xs hover:shadow-md'
              }`}
            >
              <div className="flex items-start gap-3.5 flex-1 min-w-0">
                <button
                  onClick={() => handleToggle(m.id)}
                  className="mt-0.5 text-purple-600 hover:text-purple-700 cursor-pointer shrink-0"
                  title={m.isCompleted ? 'Mark as incomplete' : 'Mark as complete'}
                >
                  <CheckCircle2
                    className={`w-5 h-5 ${
                      m.isCompleted ? 'fill-purple-600 text-white' : 'text-slate-300 hover:text-purple-400'
                    }`}
                  />
                </button>

                <div className="space-y-1 min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <span
                      className={`text-sm font-bold ${
                        m.isCompleted ? 'line-through text-slate-400' : 'text-slate-900'
                      }`}
                    >
                      {m.title}
                    </span>
                    <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-purple-100 text-purple-800">
                      {m.phaseLabel}
                    </span>
                    {m.category && (
                      <span className="text-[10px] font-medium px-2 py-0.5 rounded-full bg-slate-100 text-slate-600">
                        {m.category}
                      </span>
                    )}
                    {m.isCustom && (
                      <span className="text-[9px] font-bold uppercase tracking-wider text-indigo-600 bg-indigo-50 px-1.5 py-0.5 rounded">
                        Custom
                      </span>
                    )}
                  </div>
                  <p className="text-xs text-slate-600 leading-relaxed">
                    {m.description}
                  </p>
                </div>
              </div>

              {/* Target date & Days remaining */}
              <div className="flex items-center gap-3 shrink-0 self-end sm:self-center">
                <div className="text-right text-xs">
                  {m.calculatedDate ? (
                    <div className="flex items-center gap-1.5 text-slate-700 font-semibold justify-end">
                      <Calendar className="w-3.5 h-3.5 text-purple-600" />
                      <span>{formatDate(m.calculatedDate)}</span>
                    </div>
                  ) : null}
                  <span className="text-[11px] text-slate-400">
                    {m.targetDaysBefore === 0
                      ? 'On Event Day'
                      : `${m.targetDaysBefore} days before`}
                  </span>
                </div>

                {m.isCustom && (
                  <button
                    onClick={() => handleDelete(m.id)}
                    className="p-1.5 text-slate-400 hover:text-rose-600 rounded-lg hover:bg-rose-50 transition cursor-pointer"
                    title="Delete custom milestone"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                )}
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
};
